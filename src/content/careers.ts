import {byId} from './catalog';
import {type GroupId,type Level,type Stage} from './model';

export interface Requirement { id: string; weight: number }
export interface CareerRequirement extends Requirement {
  category: 'Core' | 'Supporting' | 'Specialization';
}
export interface Career {
  id: string;
  name: string;
  group: GroupId;
  occupation: string;
  focus: string;
  requirements: CareerRequirement[];
  project: string;
  deliverable: string;
}

// The weights are TechFluent's teaching priorities. O*NET describes occupation families.
function career(id: string, name: string, group: GroupId, occupation: string, focus: string,
  core: string, supporting: string, specialization: string, project: string, deliverable: string): Career {
  return {
    id,name,group,occupation,focus,project,deliverable,
    requirements:[
      ...core.split(' ').map(id=>({id,weight:2,category:'Core' as const})),
      ...supporting.split(' ').map(id=>({id,weight:1,category:'Supporting' as const})),
      ...specialization.split(' ').map(id=>({id,weight:1,category:'Specialization' as const})),
    ],
  };
}


export const levels: readonly Level[] = ['Entry','Intermediate','Senior'];
export const levelGoal: Record<Level,string> = {
  Entry:'Define the concept and trace a concrete example.',
  Intermediate:'Diagnose a failure, compare alternatives, and choose a test.',
  Senior:'Defend tradeoffs, define failure boundaries, and explain what you would measure.',
};
export const stageLevels: Record<Stage,Level> = {
  Foundational:'Entry', Intermediate:'Intermediate', Advanced:'Senior', Specialized:'Senior',
};

export const availableRequirements = (career: Career) => career.requirements.filter(r=>!!byId[r.id]);

export function requirementsThroughLevel(career: Career, level: Level) {
  return availableRequirements(career).filter(r=>levels.indexOf(stageLevels[byId[r.id].stage])<=levels.indexOf(level));
}
